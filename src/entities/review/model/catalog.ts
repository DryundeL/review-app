export function authorById(id: string): CatalogAuthor | undefined {
  return AUTHORS.find((author) => author.id === id);
}

export function findWork(id: string, extra: readonly MediaItem[] = []): MediaItem | undefined {
  return extra.find((work) => work.id === id) ?? WORKS.find((work) => work.id === id);
}

export function findReview(id: string, extra: readonly Review[] = []): Review | undefined {
  return extra.find((review) => review.id === id) ?? REVIEWS.find((review) => review.id === id);
}

export function reviewsForMedia(mediaId: string, extra: readonly Review[] = []): Review[] {
  return [...extra, ...REVIEWS].filter((review) => review.mediaIds.includes(mediaId));
}

export function reviewsByAuthor(authorId: string, extra: readonly Review[] = []): Review[] {
  return [...extra, ...REVIEWS].filter((review) => review.authorId === authorId);
}

export function searchWorks(query: string, extra: readonly MediaItem[] = []): MediaItem[] {
  return [...extra, ...WORKS].filter((work) => matchesQuery(query, [work.title, ...work.altTitles]));
}

export function searchReviews(query: string, extra: readonly Review[] = []): Review[] {
  return [...extra, ...REVIEWS].filter((review) =>
    matchesQuery(query, [review.title, review.excerpt, review.authorName]),
  );
}

export function searchAuthors(query: string): CatalogAuthor[] {
  return AUTHORS.filter((author) =>
    matchesQuery(query, [author.name, author.handle, ...author.taste.map((item) => item.label)]),
  );
}
